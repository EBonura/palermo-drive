// Bakes src/unbuilt-roads.js: the road segments of the tiles that the game does not build, so that the traffic graph (src/traffic-graph.js) and with it the pink guidance line
// (src/route-guide.js) never use them.
//   node assets/missions/snap-unbuilt.mjs            (about 30 seconds)
// The tiles (world/tiles/*.json) list every OpenStreetMap road. The game draws and collides only what the street polygons and the building footprints say. A road with no street
// surface under it, or one that runs through a building footprint (a passage, an arch, a covered way the game does not open), is not a road the car can drive, but the graph had
// it, so the guide could send the car across a house (the same test, BUILT in assets/missions/roadnet.mjs, filters the baked routes of snap-places.mjs).
// Each entry is a run of consecutive unbuilt segments of one road, flat x,z in metres (one decimal). The graph skips a segment when both its ends are within 0.3 m of one of them.
// Re-run this after the world tiles change (tools/tiles.py), then tools/route-check/check.mjs.
import fs from 'fs';
import path from 'path';
import { ROOT, makeGeo, BUILT } from './roadnet.mjs';

const CLASSES = new Set(['motorway', 'motorway_link', 'trunk', 'trunk_link', 'primary', 'primary_link', 'secondary', 'secondary_link', 'tertiary', 'tertiary_link', 'unclassified', 'residential', 'living_street', 'service', 'pedestrian']);   // CLASS in src/traffic-graph.js
const dir = path.join(ROOT, 'world/tiles'), geo = makeGeo(), roads = [];
for (const f of fs.readdirSync(dir)) {
  const t = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  geo.add(f.replace('.json', ''), t);
  for (const r of t.roads) if (CLASSES.has(r.k) && !r.tn && r.p.length >= 4) roads.push({ p: r.p, br: r.br });
}
const r1 = v => Math.round(v * 10) / 10, runs = []; let segs = 0, total = 0, len = 0;
for (const r of roads) {
  const p = r.p; let run = null;
  for (let i = 0; i + 3 < p.length; i += 2) {
    total++;
    if (geo.built(p[i], p[i + 1], p[i + 2], p[i + 3])) { run = null; continue; }
    segs++; len += Math.hypot(p[i + 2] - p[i], p[i + 3] - p[i + 1]);
    if (!run) { run = [r1(p[i]), r1(p[i + 1])]; runs.push(run); }
    run.push(r1(p[i + 2]), r1(p[i + 3]));
  }
}
const out = `// GENERATED by assets/missions/snap-unbuilt.mjs from the world tiles. Do not edit by hand: run the script again after the tiles change.
// The road segments the game does not build (no street surface under them, or a building footprint across them, see BUILT in assets/missions/roadnet.mjs): the traffic graph
// (src/traffic-graph.js) leaves them out, so neither traffic nor the pink guidance line uses a road that is not there. Each entry is the flat x,z of a run of consecutive segments of one road.
export const UNBUILT = ${JSON.stringify(runs)};
`;
fs.writeFileSync(path.join(ROOT, 'src/unbuilt-roads.js'), out);
console.log(`${total} road segments, ${segs} unbuilt (${Math.round(len)} m) in ${runs.length} runs; wrote src/unbuilt-roads.js ${(out.length / 1024).toFixed(0)} KB (HARD_MIN ${BUILT.HARD_MIN}, BLD_RUN ${BUILT.BLD_RUN} m)`);
