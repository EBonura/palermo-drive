// Bakes the AMAT bus routes into assets/traffic/bus-routes.js, for the whole tile area (world/manifest.json bbox).
// Source: data/bus_routes.json (tools/transit.py from the AMAT GTFS feed, CC BY 4.0, shapes and stops; includes the lines OSM lacks, e.g. the 806 to Mondello).
// Per route the busiest pattern of each direction; shapes thinned to 2 m. Stops: every GTFS stop plus the highway=bus_stop props of world/tiles/*.json.
// If data/bus_routes.json is missing the older OpenStreetMap relations (data/bus_routes_osm.json, ODbL) are used as before. Run: node assets/traffic/bake-bus.cjs
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '../..'), [bx0, bz0, bx1, bz1] = JSON.parse(fs.readFileSync(path.join(ROOT, 'world/manifest.json'))).bbox;
const LAT0 = 38.11572, LON0 = 13.36126, KX = Math.cos(LAT0 * Math.PI / 180) * 111320, KZ = 110540;
const proj = (lat, lon) => [Math.round((lon - LON0) * KX * 10) / 10, Math.round(-(lat - LAT0) * KZ * 10) / 10];
const inside = p => p[0] > bx0 && p[0] < bx1 && p[1] > bz0 && p[1] < bz1;
const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);
const rels = JSON.parse(fs.readFileSync(path.join(__dirname, '../../data/bus_routes_osm.json'))).elements
  .filter(r => /AMAT/i.test(r.tags.network || '') || /AMAT/i.test(r.tags.operator || ''))
  .filter(r => r.members.some(m => m.type === 'way'));
let stopsAll = [];
// highway=bus_stop nodes: the baked props of every tile (kind 'busstop', already in local metres)
const TD = path.join(ROOT, 'world/tiles');
for (const f of fs.readdirSync(TD)) {
  if (!f.endsWith('.json')) continue;
  for (const it of (JSON.parse(fs.readFileSync(path.join(TD, f))).props || { items: [] }).items) if (it.k === 'busstop') stopsAll.push([Math.round(it.x), Math.round(it.z)]);   // whole metres: stops are matched to the line within 10 m, and it compresses far better
}
stopsAll.sort((a, b) => Math.floor(a[0] / 100) - Math.floor(b[0] / 100) || Math.floor(a[1] / 100) - Math.floor(b[1] / 100) || a[0] - b[0] || a[1] - b[1]);
const GTFS = path.join(__dirname, '../../data/bus_routes.json');
function dp(p, tol) { // Douglas-Peucker on [[x, z], ...], iterative
  if (p.length < 3) return p;
  const keep = new Uint8Array(p.length); keep[0] = keep[p.length - 1] = 1;
  const st = [[0, p.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let m = -1, md = 0;
    const dx = p[b][0] - p[a][0], dz = p[b][1] - p[a][1], l2 = dx * dx + dz * dz || 1;
    for (let i = a + 1; i < b; i++) { const t = Math.max(0, Math.min(1, ((p[i][0] - p[a][0]) * dx + (p[i][1] - p[a][1]) * dz) / l2)), d = Math.hypot(p[i][0] - p[a][0] - dx * t, p[i][1] - p[a][1] - dz * t); if (d > md) { md = d; m = i; } }
    if (md > tol) { keep[m] = 1; st.push([a, m], [m, b]); }
  }
  return p.filter((_, i) => keep[i]);
}
if (fs.existsSync(GTFS)) {
  const G = JSON.parse(fs.readFileSync(GTFS)), stopOf = new Map(G.stops.map(s => [s.id, s]));
  const outG = [];
  for (const r of G.routes) {
    const parts = r.name.split(/\s+-\s+/), a = parts[0], z = parts[parts.length - 1];
    for (const dir of [0, 1]) {
      const pats = r.patterns.filter(q => q.direction === dir && q.shape_pts && q.shape_pts.length > 1).sort((x, y) => y.trips - x.trips || y.len - x.len);
      if (!pats.length) continue;
      const pt = pats[0], pieces = dp(pt.shape_pts.map(q => [q[0], q[1]]), 2).map(q => [Math.round(q[0] * 10) / 10, Math.round(q[1] * 10) / 10]);
      const stops = pt.stops.map(id => stopOf.get(id)).filter(Boolean).map(s => [Math.round(s.x * 10) / 10, Math.round(s.z * 10) / 10]);
      const loop = stops.length > 2 && dist(stops[0], stops[stops.length - 1]) < 120;
      outG.push({ ref: r.ref, to: (dir === 0 ? z : a).trim(), from: (dir === 0 ? a : z).trim(), loop, pieces: [pieces], stops });
    }
  }
  // stops: GTFS stops, then the OSM bus stops more than 8 m from one
  const gs = G.stops.map(s => [Math.round(s.x), Math.round(s.z)]), seen = new Set(gs.map(q => q[0] + ',' + q[1]));
  const all = gs.slice();
  for (const q of stopsAll) { if (!gs.some(g => Math.abs(g[0] - q[0]) < 8 && Math.abs(g[1] - q[1]) < 8)) all.push(q); }
  all.sort((p, q) => Math.floor(p[0] / 100) - Math.floor(q[0] / 100) || Math.floor(p[1] / 100) - Math.floor(q[1] / 100) || p[0] - q[0] || p[1] - q[1]);
  const flatG = p => p.flatMap(q => q);
  const srcG = `// Generated by assets/traffic/bake-bus.cjs from the AMAT GTFS feed (CC BY 4.0, Comune di Palermo open data) and OpenStreetMap bus stops (ODbL).
// Coordinates are local metres like palermo-data.js.
export const BUS_ROUTES = ${JSON.stringify(outG.map(r => ({ ref: r.ref, to: r.to, from: r.from, loop: r.loop, pieces: r.pieces.map(flatG), stops: flatG(r.stops) })))};
export const BUS_STOPS = ${JSON.stringify(flatG(all))};
`;
  fs.writeFileSync(path.join(__dirname, 'bus-routes.js'), srcG);
  console.log(outG.length, 'patterns of', G.routes.length, 'routes,', all.length, 'stops,', (srcG.length / 1024) | 0, 'KB;', '806:', outG.filter(r => r.ref === '806').length);
  process.exit(0);
}
const out = [];
for (const r of rels) {
  const ways = r.members.filter(m => m.type === 'way' && m.geometry && m.geometry.length > 1).map(m => m.geometry.map(g => proj(g.lat, g.lon)));
  const pieces = []; let cur = [];
  const flush = () => { if (cur.length > 1) pieces.push(cur); cur = []; };
  for (let i = 0; i < ways.length; i++) {
    let w = ways[i];
    if (!cur.length) { // orient the first way of a run towards the next one
      const nx = ways[i + 1];
      if (nx && Math.min(dist(w[0], nx[0]), dist(w[0], nx[nx.length - 1])) < Math.min(dist(w[w.length - 1], nx[0]), dist(w[w.length - 1], nx[nx.length - 1]))) w = w.slice().reverse();
      cur = w.slice(); continue;
    }
    const end = cur[cur.length - 1];
    if (dist(w[w.length - 1], end) < dist(w[0], end)) w = w.slice().reverse();
    if (dist(w[0], end) > 25) { flush(); cur = w.slice(); continue; }
    cur.push(...w.slice(dist(w[0], end) < 0.5 ? 1 : 0));
  }
  flush();
  // clip to the loaded map: keep runs of points inside the bounds
  const clipped = [];
  for (const p of pieces) {
    let run = [];
    for (const q of p) { if (inside(q)) { if (!run.length || dist(run[run.length - 1], q) > 0.05) run.push(q); } else { if (run.length > 1) clipped.push(run); run = []; } }
    if (run.length > 1) clipped.push(run);
  }
  const keep = clipped.filter(p => { let l = 0; for (let i = 1; i < p.length; i++) l += dist(p[i], p[i - 1]); return l > 150; });
  if (!keep.length) continue;
  const stops = r.members.filter(m => m.type === 'node' && /^(stop|platform)/.test(m.role) && m.lat).map(m => proj(m.lat, m.lon)).filter(inside);
  out.push({ ref: r.tags.ref || '', to: r.tags.to || r.tags.name || '', from: r.tags.from || '', loop: (r.tags.from || 'a') === (r.tags.to || 'b'), pieces: keep, stops });
}
const flat = p => p.flatMap(q => q);
const src = `// Generated by assets/traffic/bake-bus.cjs from OpenStreetMap bus route relations (AMAT Palermo).
// Map data (c) OpenStreetMap contributors, ODbL. Coordinates are local metres like palermo-data.js.
export const BUS_ROUTES = ${JSON.stringify(out.map(r => ({ ref: r.ref, to: r.to, from: r.from, loop: r.loop, pieces: r.pieces.map(flat), stops: flat(r.stops) })))};
export const BUS_STOPS = ${JSON.stringify(flat(stopsAll))};
`;
fs.writeFileSync(path.join(__dirname, 'bus-routes.js'), src);
console.log(out.length, 'routes', out.reduce((s, r) => s + r.pieces.length, 0), 'pieces', stopsAll.length, 'stops', (src.length / 1024) | 0, 'KB');
console.log(out.map(r => `${r.ref}>${r.to}[${r.pieces.length}]`).join(' '));
