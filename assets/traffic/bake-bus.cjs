// Bakes the AMAT bus routes (OpenStreetMap, ODbL) into assets/traffic/bus-routes.js.
// Inputs (Overpass JSON, cached in data/): bus_routes_osm.json ("out geom" of route=bus relations),
// optional bus_stops_osm.json (highway=bus_stop nodes). Run: node assets/traffic/bake-bus.cjs
const fs = require('fs'), path = require('path');
global.window = {}; require(path.join(__dirname, '../../palermo-data.js'));
const D = window.PALERMO_DATA, [bx0, bz0, bx1, bz1] = D.bounds;
const LAT0 = 38.11572, LON0 = 13.36126, KX = Math.cos(LAT0 * Math.PI / 180) * 111320, KZ = 110540;
const proj = (lat, lon) => [Math.round((lon - LON0) * KX * 10) / 10, Math.round(-(lat - LAT0) * KZ * 10) / 10];
const inside = p => p[0] > bx0 && p[0] < bx1 && p[1] > bz0 && p[1] < bz1;
const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);
const rels = JSON.parse(fs.readFileSync(path.join(__dirname, '../../data/bus_routes_osm.json'))).elements
  .filter(r => /AMAT/i.test(r.tags.network || '') || /AMAT/i.test(r.tags.operator || ''))
  .filter(r => r.members.some(m => m.type === 'way'));
let stopsAll = [];
try { stopsAll = JSON.parse(fs.readFileSync(path.join(__dirname, '../../data/bus_stops_osm.json'))).elements.map(n => proj(n.lat, n.lon)).filter(inside); } catch (e) { /* optional */ }
const out = [];
for (const r of rels) {
  const ways = r.members.filter(m => m.type === 'way' && m.geometry && m.geometry.length > 1).map(m => m.geometry.map(g => proj(g.lat, g.lon)));
  const pieces = []; let cur = [];
  const flush = () => { if (cur.length > 1) pieces.push(cur); cur = []; };
  for (let i = 0; i < ways.length; i++) {
    let w = ways[i];
    if (!cur.length) { // orient the first way of a run towards the next one
      const nx = ways[i + 1];
      if (nx && Math.min(dist(w[0], nx[0]), dist(w[0], nx[nx.length - 1])) < Math.min(dist(w[w.length - 1], nx[0]), dist(w[w.length - 1], nx[nx.length - 1]))) w = w.slice().reverse();
      cur = w.slice(); continue;
    }
    const end = cur[cur.length - 1];
    if (dist(w[w.length - 1], end) < dist(w[0], end)) w = w.slice().reverse();
    if (dist(w[0], end) > 25) { flush(); cur = w.slice(); continue; }
    cur.push(...w.slice(dist(w[0], end) < 0.5 ? 1 : 0));
  }
  flush();
  // clip to the loaded map: keep runs of points inside the bounds
  const clipped = [];
  for (const p of pieces) {
    let run = [];
    for (const q of p) { if (inside(q)) { if (!run.length || dist(run[run.length - 1], q) > 0.05) run.push(q); } else { if (run.length > 1) clipped.push(run); run = []; } }
    if (run.length > 1) clipped.push(run);
  }
  const keep = clipped.filter(p => { let l = 0; for (let i = 1; i < p.length; i++) l += dist(p[i], p[i - 1]); return l > 150; });
  if (!keep.length) continue;
  const stops = r.members.filter(m => m.type === 'node' && m.role === 'stop' && m.lat).map(m => proj(m.lat, m.lon)).filter(inside);
  out.push({ ref: r.tags.ref || '', to: r.tags.to || r.tags.name || '', from: r.tags.from || '', loop: (r.tags.from || 'a') === (r.tags.to || 'b'), pieces: keep, stops });
}
const flat = p => p.flatMap(q => q);
const src = `// Generated by assets/traffic/bake-bus.cjs from OpenStreetMap bus route relations (AMAT Palermo).
// Map data (c) OpenStreetMap contributors, ODbL. Coordinates are local metres like palermo-data.js.
export const BUS_ROUTES = ${JSON.stringify(out.map(r => ({ ref: r.ref, to: r.to, from: r.from, loop: r.loop, pieces: r.pieces.map(flat), stops: flat(r.stops) })))};
export const BUS_STOPS = ${JSON.stringify(flat(stopsAll))};
`;
fs.writeFileSync(path.join(__dirname, 'bus-routes.js'), src);
console.log(out.length, 'routes', out.reduce((s, r) => s + r.pieces.length, 0), 'pieces', stopsAll.length, 'stops', (src.length / 1024) | 0, 'KB');
console.log(out.map(r => `${r.ref}>${r.to}[${r.pieces.length}]`).join(' '));
