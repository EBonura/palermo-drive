// Bundles Trystero (WebRTC peer to peer, no server of ours) into src/p2p/trystero.js so the dev server (no bundler) and the
// production build both load the same file from this site. Run after changing the trystero version: node tools/build/vendor-trystero.mjs
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(HERE, '../..');
const entry = `
import { joinRoom as nostr, getRelaySockets as nostrSockets, defaultRelayUrls as nostrRelays, selfId, pauseRelayReconnection, resumeRelayReconnection } from '@trystero-p2p/nostr';   // Nostr only: the board game uses the same (BitTorrent and MQTT were removed on 8 Nov, nothing used them)
export const strategies = { nostr: { joinRoom: nostr, sockets: nostrSockets, relays: nostrRelays } };
import { schnorr } from '@noble/secp256k1';   // already inside the Nostr strategy; src/p2p/presence.js signs its own events with it
export { selfId, pauseRelayReconnection, resumeRelayReconnection, schnorr };
`;
const r = await esbuild.build({ stdin: { contents: entry, resolveDir: HERE }, bundle: true, format: 'esm', platform: 'browser', target: ['chrome90', 'safari15', 'firefox90'],
  minify: true, legalComments: 'none', write: false, nodePaths: [path.join(HERE, 'node_modules')], logLevel: 'warning' });
const out = path.join(ROOT, 'src/p2p/trystero.js');
fs.writeFileSync(out, '// generated by tools/build/vendor-trystero.mjs from @trystero-p2p (MIT, https://github.com/dmotz/trystero). Do not edit.\n' + r.outputFiles[0].text);
console.log(out, (r.outputFiles[0].contents.length / 1024).toFixed(1) + ' KB');
