import puppeteer from 'puppeteer-core';
import { startServer } from './serve.mjs';
const { server, port } = await startServer(process.argv[2], '');
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal','--enable-gpu','--ignore-gpu-blocklist'] });
const page = await b.newPage();
const seen = new Set();
page.on('console', m => { const t = m.text(); if (true) { const k=t.slice(0,300); if(!seen.has(k)){seen.add(k); console.log('['+m.type()+']', t.slice(0, +process.argv[4]||1500)); }} });
page.on('pageerror', e => console.log('pageerror', e.message.slice(0,300)));
await page.goto(`http://127.0.0.1:${port}/?${process.argv[3]||'debug'}`);
await new Promise(r=>setTimeout(r,25000));
await b.close(); server.close();
