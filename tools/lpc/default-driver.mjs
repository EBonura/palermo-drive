// Bakes the default driver: the person that sits in every vehicle until the player makes their own in the Garage. It is src/driver-compose.js's defaultSpec() composed in a real browser
// and kept the way a saved driver is (src/driver.js: the cropped front, left and back frames next to each other, one PNG), written to src/driver-default.js as a data URL so that driving
// downloads no layer. Run it again after changing defaultSpec(), the layers, the extras (assets/peds/lpc/extras.js) or the crop in src/driver.js:
//   node tools/lpc/default-driver.mjs [--png out.png]      (--png also writes the strip as a file, to look at it)
// Needs Chrome (the path below) and the packages of tools/build (three, puppeteer-core). src/driver-default.js has to exist already, with any content: driver.js imports it.
import { createRequire } from 'module'; import fs from 'fs'; import path from 'path'; import http from 'http'; import { fileURLToPath } from 'url';
const here = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(here, '../..');
const puppeteer = createRequire(path.join(ROOT, 'tools/build/package.json'))('puppeteer-core');
const CHROME = process.env.CHROME || (process.env.PD_CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome');
const MIME = { '.js': 'text/javascript', '.json': 'application/json', '.png': 'image/png', '.html': 'text/html' };
const BLANK = `<!doctype html><script type="importmap">{"imports":{"three":"/tools/build/node_modules/three/build/three.module.js"}}</script>`;   // three from the local package, not the CDN

const server = http.createServer((req, res) => {
  const u = decodeURIComponent(req.url.split('?')[0]);
  if (u === '/blank.html') { res.writeHead(200, { 'content-type': 'text/html' }); return res.end(BLANK); }
  const f = path.join(ROOT, u);
  if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { 'content-type': MIME[path.extname(f)] || 'application/octet-stream' }); res.end(fs.readFileSync(f));
});
await new Promise(r => server.listen(0, '127.0.0.1', r));
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new' });
try {
  const page = await browser.newPage(); page.on('pageerror', e => { throw e; });
  await page.goto(`http://127.0.0.1:${server.address().port}/blank.html`);
  const png = await page.evaluate(async () => {
    const dc = await import('/src/driver-compose.js'); await dc.loadManifest();
    const out = await dc.compose(dc.defaultSpec());
    const { driver } = await import('/src/driver.js'); driver.set(out.sit, out.spec);   // the same crop and encoding as a driver the player saves
    return JSON.parse(localStorage.getItem('pd.driver')).png;
  });
  if (!png.startsWith('data:image/png;base64,')) throw new Error('no picture');
  fs.writeFileSync(path.join(ROOT, 'src/driver-default.js'),
    `// GENERATED by tools/lpc/default-driver.mjs, do not edit: the default driver (src/driver-compose.js defaultSpec()) as src/driver.js keeps a saved one, a PNG of the front, left and back frames.\nexport const DEFAULT_DRIVER_PNG = '${png}';\n`);
  const o = process.argv.indexOf('--png'); if (o > 0) fs.writeFileSync(process.argv[o + 1], Buffer.from(png.split(',')[1], 'base64'));
  console.log('src/driver-default.js written,', png.length, 'characters');
} finally { await browser.close(); server.close(); }
